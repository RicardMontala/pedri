import numpy as np

from math import pi
from math import sqrt

from scipy.optimize import minimize
from scipy.interpolate import make_interp_spline

import logging
logger = logging.getLogger(__name__)


def construct_spline(xy, n_points=200, split_points=None):
    '''
    Construct the airfoil coordinates following cubic spline curves interpolating the input points.

    If split_points are provided, separate spline curves are constructed between consecutive splitting points.
    This aims to mimic the airfoil surface generated by Gmsh.

    xy: array (N,2)
        N points defining the x and y coordinates of the airfoil.
        It assumes that the points are already concatenated in the list following the airfoil surface.
    
    n_points: int, optional
        Number of points used to discretize each spline segment.

    split_points: array (n_split, 2), optional
        Coordinates of the N_split points at which the spline is split
        into separate segments. If None, a single spline is constructed
        using all input points.

    Output: array (n_points*n_split, 2)
        x and y coordinates of the airfoil reconstructed from the spline.
    '''
    
    xy = np.asarray(xy)

    # Find the indices corresponding to the split points
    # (it finds the closer in the airfoil xy list)
    if split_points is None:
        ids = [0]
    else:
        ids = []
        spline_segments = np.zeros((len(split_points), 2), dtype=int)
        for sp_point in split_points:
            dist = np.sqrt(np.power(xy[:,0] - sp_point[0], 2) + np.power(xy[:,1] - sp_point[1], 2))
            ids.append(np.argmin(dist))

        ids = np.sort(np.asarray(ids, dtype=int))

    # Construct the spline segments. Each "spline_segment" element contains the list of xy coordinates for that segment
    spline_segments = []
    for i in range(len(ids)):
        start = ids[i]
        end = ids[(i + 1) % len(ids)]

        # Normal segment
        if end > start:
            segment = xy[start:end + 1]

        # Wrapped segment: start -> end of array -> beginning -> end
        else:
            segment = np.vstack((xy[start:], xy[:end + 1]))
        
        spline_segments.append(segment)

    # Fit xy coordinates to the defined spline segments and construct a single concatenated surface
    xy_new = []
    for i, xy_segment in enumerate(spline_segments):

        # Original parameter
        u = np.arange(len(xy_segment))

        # Cubic splines
        spline_x = make_interp_spline(u, xy_segment[:,0], k=3)
        spline_y = make_interp_spline(u, xy_segment[:,1], k=3)

        # New parameter with extra sampling
        t = np.linspace(u[0], u[-1], n_points)

        # Obtain new coordinates
        xy_new_segment = np.column_stack((spline_x(t), spline_y(t)))

        # Remove repeated points (start and end points of each segment)
        if i > 0:
            xy_new_segment = xy_new_segment[1:]
        if i == len(spline_segments)-1:
            xy_new_segment = xy_new_segment[:-1]

        # Append to the final list
        xy_new.append(xy_new_segment)

    return np.vstack(xy_new)


def order_airfoil(xy):
    """
    Return airfoil coordinates in the convention: TE -> upper -> LE -> lower -> TE.

    xy: array (n_points, 2)
        Array containing the xy coordinates of the N_points defining the airfoil geometry.
        It assumes that the points are already concatenated in the list following the airfoil surface.

    output: array (n_points, 2)
        Array containing the same xy coordinates but following the convention
    """

    xy = np.asarray(xy)

    # Find leading and trailing edge
    le_idx = np.argmin(xy[:, 0])
    te_idx = np.argmax(xy[:, 0])

    # Split list in two portions
    # surface_1: TE -> LE
    # surface_2: LE -> TE
    if te_idx > le_idx:
        surface_1 = np.vstack((xy[te_idx:], xy[:le_idx + 1]))
        surface_2 = xy[le_idx:te_idx + 1]

    else: # le_idx > te_idx
        surface_1 = xy[te_idx:le_idx + 1]
        surface_2 = np.vstack((xy[le_idx:], xy[:te_idx + 1]))

    # Determine which surface is upper (approach valid for not extremely cambered airfoils)
    if np.mean(surface_1[:, 1]) > np.mean(surface_2[:, 1]):
        upper = surface_1
        lower = surface_2

    else:  # need to flip the ordering
        upper = surface_2[::-1]
        lower = surface_1[::-1]

    # Concatenate them back (avoid repeating the LE)
    ordered = np.vstack([upper, lower[1:]])

    return ordered


def create_initial_distribution_ctlPts(xy, NctePts_upper, NctePts_lower, distribution='linear'):
    '''
    Creates an initial set of N=(NctePts_upper + NctePts_lower) control points to start the optimization process of matchin airfoil shape.

    xy: array(n_points, 2)
        List of (x,y) points defining the airfoil geometry. The control points will fall within this curve (as an initial guess)
        Assumes that airfoil is already ordered uisng the convention TE -> upper -> LE -> lower -> TE

    Ncte_upper: int
        Number of desired control points in the upper surface.

    Ncte_lower: int
        Number of desired control points in the lower surface.

    distribution: string, optional
        Distribution used to place the points along the airfoil xy surface. Currently available ['linear', 'cosine']

    output: ((Ncte_upper+Ncte_lower)*2,)
        List of control points already in the optimizer format [p01_x, p01_y, p02_x, p02_y, ...]
    '''

    # Find leading edge location
    id_le = np.argmin(xy[:,0])

    # Split into upper and lower surfaces
    upper = xy[:id_le+1]
    lower = xy[id_le:]

    # Find spaced points for both surfaces according to the number of control points for each surface
    def _distribute_points(xy_surface, Npoints, distribution):

        # Distance between consecutive points
        dist = np.sqrt((xy_surface[1:,0]-xy_surface[:-1,0])**2 + (xy_surface[1:,1]-xy_surface[:-1,1])**2)

        # Total distance from the starting point until correspinding point
        cumulative_dist = np.concatenate(([0], np.cumsum(dist)))

        # Normalized arc length
        s = cumulative_dist / cumulative_dist[-1]

        # Distribution of the desired points
        if distribution == 'linear':
            s_target = np.linspace(0, 1, Npoints + 2)[1:-1]
        elif distribution == 'cosine':
            theta = np.linspace(0, np.pi, Npoints + 2)[1:-1]
            s_target = 0.5 * (1 - np.cos(theta))
        else:
            raise ValueError(f"Unknown distribution {distribution}. Use 'linear' or 'cosine'.")

        # Convert normalized arc length into actual arc length
        target_dist = s_target * cumulative_dist[-1]

        # Find closest existing points
        ids = np.array([np.argmin(np.abs(cumulative_dist - d)) for d in target_dist])

        return ids

    upper_ids = _distribute_points(upper, NctePts_upper, distribution)
    lower_ids = _distribute_points(lower, NctePts_lower, distribution)

    return np.vstack((upper[upper_ids], lower[lower_ids])).flatten()


def get_t(x, ctlPts):
    '''
    For given x-coordinates, what Bezier parameters t corresponds to them.

    x: array (n_points,)
        Desired x-coordinate.
    
    ctrPts: array (3, 2)
        Three control points P0, P1, P2 defining the Bezier curve:
        ((P0_x, P0_y), (P1_x, P1_y), , (P2_x, P2_y)).

    Output 1: array (n_points,)
        t values corresponding to the x coordinates initially provided
    '''

    # Extract the three x-coordinates of the control points
    a = ctlPts[0,0]
    b = ctlPts[1,0]
    c = ctlPts[2,0]

    # Find the roots of the resulting equation for t: (a-2b+c)*t^2 + 2(b-a)*t + (a-x)=0
    # A*t^2 + B*t + C = 0 -> t = (-B +- sqrt(B^2-4AC))/2A
    A = c + a - 2*b
    B = 2*(b - a)
    C = a - x

    if abs(A) < 1e-12:
        return -C / B

    discriminant = B**2 - 4*A*C
    discriminant = np.maximum(discriminant, 0.0)

    sqrt_d = np.sqrt(discriminant)

    t0 = (-B + sqrt_d) / (2*A)
    t1 = (-B - sqrt_d) / (2*A)

    valid0 = (t0 >= -1e-10) & (t0 <= 1 + 1e-10) # Should be between 0 and 1
    
    return np.where(valid0, t0, t1) # Return t0 if it fall within [0,1], otherwise return t1


def quadratic_bezier(t, ctlPts):
    '''
    Evaluate xy-coordinates of a quadratic Bezier curve at given t values.
    In Bezier quadratic curves, P0 and P2 are the end points, and P1 the control point:
    B(t) = (1-t)[(1-t)P0 + tP1] + t[(1-t)P1 + tP2]

    t: array (n_points,) (between 0 and 1 each value)
        Bezier parameter
    
    ctlPts: array (3,2)
        Control points P0, P1, and P2 to construct the Bezier curve. X and y coordinates.

    Output 1: array (n_points,)
        x-coordinate corresponding to parameter t

    Output 2: array (n_points,)
        y-coordinate corresponding to parameter t
    '''

    x =(1-t)*((1-t)*ctlPts[0,0]+t*ctlPts[1,0])+t*((1-t)*ctlPts[1,0]+t*ctlPts[2,0])
    y =(1-t)*((1-t)*ctlPts[0,1]+t*ctlPts[1,1])+t*((1-t)*ctlPts[1,1]+t*ctlPts[2,1])

    return x, y


def bezier_airfoil(x_coords, ctlPts):
    '''
    Geometry-generation function. Given a set of Bezier control points, generate the complete airfoil surface.
    The function uses te midpoints between control points to determine where one Bezier segment transitions into the next.

    x_coords: array (n_points, )
        List of x-coordinates where you want the airfoil surface to be evaluated (corresponding y coordinate will be found).
        x_coords must follow the convention ordering: TE -> upper -> LE -> lower -> TE. Use function "order_airfoil" for so.
        LE is (0,0) and TE is (1,0)

    ctlPts: array (N_ctePts, 2)
        List of N_ctePts control points (x,y) defining the airfoil shape.

    output: array (n_points, 2)
        List of xy-coordinates defining the airfoil surface using the control points defined in ctlPts
    '''

    x_coords = np.asarray(x_coords)
    n_ctl = len(ctlPts)

    # Find leading edge
    le_idx = np.argmin(x_coords)

    # Split into upper and lower surfaces
    x_upper = x_coords[:le_idx + 1]
    x_lower = x_coords[le_idx:]

    # Split control points into upper and lower
    le_ctl_idx = (n_ctl - 1) // 2
    ctlpts_upper = ctlPts[:le_ctl_idx + 1]
    ctlpts_lower = ctlPts[le_ctl_idx:]

    # Function to evaluate each surface
    def _evaluate_surface(x_surface, ctlpts_surface):

        y_surface = np.empty_like(x_surface)

        segments = []

        for j in range(len(ctlpts_surface) - 2):

            if j == 0:
                p0 = ctlpts_surface[0]
                p1 = ctlpts_surface[1]
                p2 = 0.5 * (ctlpts_surface[1] + ctlpts_surface[2])

            elif j == len(ctlpts_surface) - 3:
                p0 = 0.5 * (ctlpts_surface[-3] + ctlpts_surface[-2])
                p1 = ctlpts_surface[-2]
                p2 = ctlpts_surface[-1]

            else:
                p0 = 0.5 * (ctlpts_surface[j] + ctlpts_surface[j+1])
                p1 = ctlpts_surface[j+1]
                p2 = 0.5 * (ctlpts_surface[j+1] + ctlpts_surface[j+2])

            segments.append(np.array([p0, p1, p2]))

        for segment in segments:

            xmin = min(segment[0,0], segment[2,0])
            xmax = max(segment[0,0], segment[2,0])

            mask = ((x_surface >= xmin - 1e-10) & (x_surface <= xmax + 1e-10))

            x = x_surface[mask]

            t = get_t(x, segment)

            _, y = quadratic_bezier(t, segment)

            y_surface[mask] = y

        return y_surface

    # Appy evaluation for the upper and lower surfaces
    y_upper = _evaluate_surface(x_upper, ctlpts_upper)
    y_lower = _evaluate_surface(x_lower, ctlpts_lower)

    # Reconstruct exactly the same ordering as x_coords
    y = np.concatenate([y_upper, y_lower[1:]])

    return np.column_stack([x_coords, y])


def transform_ctlpts(params, n_top, n_bot):
    '''
    Transform the outputs from a given optimizer (list of params) into a form that's suitable for the bezier function input ctlPts.
    params = [px1, py1, px2, py2,...,pxn, pyn]

    n_top: int
        Number of top control points
    
    n_bot: int
        Number of bottom control points

    output:
        Control points of the Bezier curves in the suitable format, i.e.,  ((px1, py1), (px2, py1), ...).
    '''

    # This points are fixed and added here, otherwise we would change the angle of attack
    te = [1.0, 0.0]
    le = [0.0, 0.0]
    
    ctlpts = []

    # Construct the control points following the convention: TE -> upper -> LE -> lower -> TE
    # Append trailing edge
    ctlpts.append(te)

    # Append top points
    for i in range(0, n_top*2, 2):
        ctlpts.append([params[i], params[i+1]])

    # Append leading edge
    ctlpts.append(le)

    # Append bottom points
    for i in range(n_top*2, len(params), 2):
        ctlpts.append([params[i], params[i+1]])

    # Append trailing edge again
    ctlpts.append(te)
        
    return np.array(ctlpts)


def parametrize_airfoil(target_airfoil,  NctePts_upper=3, NctePts_lower=3,
                        split_points=np.array([[0.2,1.0],[1.0,0.0],[0.2,-1.0]]),
                        n_spline=100, distribution='cosine', maxIter=10000):
    '''
    From a list of xy points defining the airfoil geometry, create a mathching airfoil using Bezier curves.
    It generates the gemoetry using N = (NctePts_upper + NctePts_lower) control points, plus two extra control points:
    one at the LE (0,0) and the other at the TE (1,0).

    target_airfoil: array (n_points, 2)
        List of n_points defining the (x,y) points of the airfoil.
        This is usually the .dat taken from airfoiltools.com.
        Points should go from x=[0,1].

    NctePts_upper: int
        Number of desired control points in the upper surface
    
    NctePts_lower: int
        Number of desired control points in the lower surface

    split_points: array (n_split, 2)
        Coordinates of the n_split points at which the spline is split
        into separate segments. If None, a single spline is constructed
        using all input points.
        The default points split the geometry into three curves: the upper
        surface, the leading-edge region, and the lower surface. This helps
        prevent undesirable geometries from being generated during the
        creation of the initial spline.

    n_spline: int, optional
        Number of points used to reconstruct the initial spline which is
        then parametrized using the Bezier curves.

    distribution: string, optional
        How to distribute the intial control points to start optimizing.
        'cosine' or 'linear'

    maxIter: int, optional
        Maximum number of iterations allowed during the optimization process.

    output 1: array (NctePts_upper + NctePts_lower + 2, 2)
        List of obtained control points
    
    ouutput 2: array(n_points, 2)
        xy points of the matched airfoil
    '''

    target_airfoil = np.asarray(target_airfoil)

    # Create the spline of the airfoil according to the splitting points used in gmsh
    xy_spline = construct_spline(target_airfoil, n_points=n_spline, split_points=split_points)

    # Order in the convenient order used in the following functions
    xy_spline = order_airfoil(xy_spline)

    # List of x points to evaluate the generated airfoil using Bezier curves
    x_eval = xy_spline[:,0]

    # Initial guess provided to the optimizer (x1, y1, x2, y2, x3, y3, ..., x_N, y_N)
    initial_ctePte = create_initial_distribution_ctlPts(xy_spline, NctePts_upper, NctePts_lower, distribution=distribution)

    # Define the cost function to find the matching airfoil. We use the summ of squared error of the y-coordinate (is what we find)
    def shape_match(control_pts, x_eval=x_eval, xy_spline=xy_spline):

        '''
        Create cost function to evalute the matching between the created Bezier curve and the original (x,y) coordinates.

        control_pts: ndarray (n,)
            Contains the n parameters optimized
        '''

        # Create Bezier airfoil surface with current parametrs "control_pts"
        try:
            bezier_xy = np.array(bezier_airfoil(x_eval, transform_ctlpts(control_pts, NctePts_upper, NctePts_lower)))

            # Return cost function
            return np.sum((bezier_xy[:,1] - xy_spline[:,1])**2) 
        
        except Exception:
            return 1e10 # When finding an invalid gemoetry, which breaks the logic of the Bezier curves, impose a high cost

    # Minimize the cost function to obtain the control points generating the matching airfoil
    res = minimize(shape_match, initial_ctePte, method='L-BFGS-B', tol=1e-10, options={'maxiter':maxIter})
    logger.info(f'MATCHING AIRFOIL CONVERGENCE')
    logger.info("Optimization successful: %s", res.success)
    logger.info("Iterations: %d", res.nit)
    logger.info("Function evaluations: %d", res.nfev)
    logger.info("Final objective: %.6e", res.fun)

    # Recover the format of the control points from the solution
    ctePts = transform_ctlpts(res.x, NctePts_upper, NctePts_lower)

    # Create the airfoil xy gemoetry
    matched_airfoil = np.array(bezier_airfoil(x_eval, ctePts))

    return ctePts, matched_airfoil
